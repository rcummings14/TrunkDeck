    int count, filled;
    int seq = -1;
    final byte[][] blocks = new byte[16][];

    /** Feed one explicit MFID 0x90 link-control word. Returns a decoded alias only when a whole train checks out. */
    public synchronized Decoded feed(P25Framer.LinkControl lc) {
        if (lc == null || lc.b.length < 9 || lc.mfid != 0x90 || (lc.lcf & 0xC0) != 0) return null;
        int op = lc.opcode();
        if (op == 0x15) {
            count = lc.b[4] & 0x0F;
            seq = (lc.b[7] & 0xff) >>> 4;
            filled = 0;
            for (int i = 0; i < blocks.length; i++) blocks[i] = null;
            return null;
        }
        if (op != 0x17 || count == 0) return null;
        int index = lc.b[2] & 0x0F;
        int blockSeq = (lc.b[3] & 0xff) >>> 4;
        if (index < 1 || index > count || blockSeq != seq) return null;
        if (blocks[index] == null) filled++;
        blocks[index] = new byte[] {lc.b[3], lc.b[4], lc.b[5], lc.b[6], lc.b[7], lc.b[8]};
        if (filled < count) return null;
        Decoded d = decode();
        if (d != null) { count = 0; filled = 0; for (int i = 0; i < blocks.length; i++) blocks[i] = null; }
        return d;
    }

    private Decoded decode() {
        int nNibs = count * 11;
        if (nNibs < 16) return null;
        int[] nibs = new int[nNibs];
        int p = 0;
        for (int i = 1; i <= count; i++) {
            byte[] blk = blocks[i];
            if (blk == null) return null;
            nibs[p++] = blk[0] & 0x0F;
            for (int j = 1; j < 6; j++) { nibs[p++] = (blk[j] & 0xff) >>> 4; nibs[p++] = blk[j] & 0x0F; }
        }
        byte[] raw = new byte[nNibs / 2];
        for (int i = 0; i < raw.length; i++) raw[i] = (byte) ((nibs[i * 2] << 4) | nibs[i * 2 + 1]);
        int chars = LENGTH[raw[7] & 0xff];
        int body = 7 + chars * 2;
        if (chars == 0 || raw.length < body + 2) return null;
        int expect = ((raw[body] & 0xff) << 8) | (raw[body + 1] & 0xff);
        if (crc16gsm(raw, body) != expect) return null;
        int wacn = ((raw[0] & 0xff) << 12) | ((raw[1] & 0xff) << 4) | ((raw[2] & 0xff) >>> 4);
        int system = ((raw[2] & 0x0f) << 8) | (raw[3] & 0xff);
        int radio = ((raw[4] & 0xff) << 16) | ((raw[5] & 0xff) << 8) | (raw[6] & 0xff);
        String alias = descramble(raw, 7, chars * 2).stripTrailing();
        if (alias.isEmpty() || radio <= 0 || radio > 0xFFFFFF) return null;
        return new Decoded(wacn, system, radio, alias);
    }

    /** CRC-16/GSM over {@code raw[0, len)}: poly 0x1021, init 0, no reflection, final complement. */
    static int crc16gsm(byte[] raw, int len) {
        int crc = 0;
        for (int j = 0; j < len; j++) {
            crc ^= (raw[j] & 0xff) << 8;
            for (int i = 0; i < 8; i++) crc = ((crc & 0x8000) != 0) ? ((crc << 1) ^ 0x1021) : (crc << 1);
            crc &= 0xFFFF;
        }
        return (~crc) & 0xFFFF;
    }

    static String descramble(byte[] enc, int off, int len) {
        int acc = len & 0xFFFF;
        byte[] out = new byte[len];
        for (int i = 0; i < len; i++) {
            int e = enc[off + i] & 0xff;
            int lcg = (acc * 293 + 0x72E9) & 0xFFFF;
            int inter = (SUB[e] - (lcg >>> 8)) & 0xff;
            int modulus = (lcg & 0xff) | 1;
            out[i] = (byte) ((inter * INV[modulus >>> 1]) & 0xff);
            acc = (acc + e + 1) & 0xFFFF;
        }
        StringBuilder s = new StringBuilder(len / 2);
        for (int i = 0; i + 1 < out.length; i += 2) {
            int cp = ((out[i] & 0xff) << 8) | (out[i + 1] & 0xff);
            if (cp > 31 && cp < 128) s.append((char) cp);
        }
        return s.toString();
    }
